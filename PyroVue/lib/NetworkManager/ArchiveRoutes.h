#ifndef ARCHIVE_ROUTES_H
#define ARCHIVE_ROUTES_H

#include <stdint.h>

#include <functional>

#include "RunLogTypes.h"

class AsyncWebServer;
class ArchiveResponse;
class RunLogService;

// Bounded HTTP transport for /api/cmd and /api/runs*.
//
// Request callbacks only assemble a bounded body or reserve a bodyless slot.
// Filesystem work and command execution happen from poll() on the Arduino
// owner loop.  A Request Continuation weak pointer keeps the connection alive
// without retaining the raw request.
class ArchiveRoutes {
public:
    ArchiveRoutes();
    ~ArchiveRoutes();
    ArchiveRoutes(const ArchiveRoutes&) = delete;
    ArchiveRoutes& operator=(const ArchiveRoutes&) = delete;

    // Called once during setup, before begin().  The identity is copied and
    // never regenerated by the transport.
    void setIdentity(const DeviceIdentity& identity);

    // Invoked after every accepted command, including one whose effect failed.
    // The parent broadcasts its authoritative current state from this callback.
    void onStateChanged(std::function<void()> stateChanged);

    // logger is null on monitor targets; archive routes then report 404.
    void begin(AsyncWebServer& server,
               std::function<CommandResult(const CommandRequest&)>& commandHandler,
               RunLogService* logger);
    void poll(uint32_t nowMs);

private:
    friend class ArchiveResponse;

    // Called by ArchiveResponse's destructor once the response object is gone.
    void releaseResponseSlot(uint8_t slotIndex, uint32_t generation);

    struct Impl;
    Impl* impl_;
};

#endif  // ARCHIVE_ROUTES_H
